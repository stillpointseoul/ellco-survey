export type Level = {
  score: 5 | 4 | 3 | 2 | 1;
  label: string;
  headline: string;
  points: string[];
};

export type Question = {
  id: string;
  no: number;
  section: string;
  title: string;
  criteria: string[];
  levels: Level[];
};

const LEVEL_LABELS: Record<number, string> = {
  5: "매우 우수함",
  4: "우수함",
  3: "기본적임",
  2: "부적합함",
  1: "매우 부적합함",
};

function levels(
  headlines: [string, string, string, string, string],
  rows: string[][]
): Level[] {
  const scores = [5, 4, 3, 2, 1] as const;
  return scores.map((score, i) => ({
    score,
    label: LEVEL_LABELS[score],
    headline: headlines[i],
    points: rows.map((row) => row[i]),
  }));
}

